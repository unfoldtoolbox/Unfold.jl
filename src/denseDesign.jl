# Everything specific to UnfoldLinearModelContinuousTimeDenseDesign: a deconvolution model
# identical to UnfoldLinearModelContinuousTime, but storing the time-expanded designmatrix as a
# dense Matrix instead of a SparseMatrixCSC. Everything else (design, fit, solver, predict,
# effects, io) flows through the ContinuousTimeTrait or generic AbstractMatrix dispatch.

"""
    DesignMatrixLinearModelContinuousTimeDense
Like `DesignMatrixLinearModelContinuousTime`, but the time-expanded designmatrix is stored as a
dense `Matrix` instead of a `SparseMatrixCSC`. The (sparse) time-expanded matrix generated by the
existing `time_expand` machinery is converted on construction.
"""
struct DesignMatrixLinearModelContinuousTimeDense{T} <: AbstractDesignMatrix{T}
    formula::FormulaTerm # "Array of formulas"
    modelmatrix::Matrix{T} #"A concatenated dense time-expanded designmatrix."
    events::DataFrame #"Event table with all events"
end

DesignMatrixLinearModelContinuousTimeDense(args...) =
    DesignMatrixLinearModelContinuousTimeDense{Float64}()
DesignMatrixLinearModelContinuousTimeDense{T}() where {T} =
    DesignMatrixLinearModelContinuousTimeDense{T}(
        FormulaTerm(:empty, :empty),
        Matrix{T}(undef, 0, 0),
        DataFrame(),
    )


"""
Concrete type to implement an deconvolution LinearModel with a dense time-expanded designmatrix
(instead of the `SparseMatrixCSC` of `UnfoldLinearModelContinuousTime`). Same user-facing
interface (`formula + events + continuous data + BasisFunction`) and same default solver
(`solver_default`). Cross-validation & regularized solvers are not implemented.
`.design` contains the formula + times dict
`.designmatrix` contains a `DesignMatrix`
`modelfit` is a `Any` container for the model results
"""
mutable struct UnfoldLinearModelContinuousTimeDenseDesign{T} <: UnfoldModel{T}
    design::Vector{<:Pair{<:Any,<:Tuple}}
    designmatrix::Vector{<:DesignMatrixLinearModelContinuousTimeDense{T}}
    modelfit::AbstractModelFit
end


# empty model
UnfoldLinearModelContinuousTimeDenseDesign(args...) =
    UnfoldLinearModelContinuousTimeDenseDesign{Float64}(args...)
UnfoldLinearModelContinuousTimeDenseDesign{T}() where {T} =
    UnfoldLinearModelContinuousTimeDenseDesign{T}([:empty => ()])
# only design specified
UnfoldLinearModelContinuousTimeDenseDesign{T}(d::Vector{<:Pair}) where {T} =
    UnfoldLinearModelContinuousTimeDenseDesign{T}(
        d,
        DesignMatrixLinearModelContinuousTimeDense{T}(),
    )
# matrix not a vector of matrix
UnfoldLinearModelContinuousTimeDenseDesign{T}(d::Vector{<:Pair}, X::AbstractDesignMatrix) where {T} =
    UnfoldLinearModelContinuousTimeDenseDesign{T}(d, [X])
# no modelfit
UnfoldLinearModelContinuousTimeDenseDesign{T}(
    d::Vector{<:Pair},
    X::Vector{<:AbstractDesignMatrix{T}},
) where {T} = UnfoldLinearModelContinuousTimeDenseDesign{T}(deepcopy(d), X, LinearModelFit{T,2}())

# all @traitfn machinery (check_data, coeftable, times, get_basis_names, residuals, predict,
# effects) works for the dense model through this single impl
@traitimpl ContinuousTimeTrait{UnfoldLinearModelContinuousTimeDenseDesign}

# dense time-expanded designmatrices are concatenated like the sparse ones. Dispatch on the
# designmatrix type, not on the matrix type: a `Vector{<:Matrix}` is also the mass-univariate
# modelmatrix, which has to stay a vector of per-event matrices.
StatsModels.modelmatrix(d::Vector{<:DesignMatrixLinearModelContinuousTimeDense}) =
    extend_to_larger(modelmatrices.(d)...)
