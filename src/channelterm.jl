"""
    bychannel(sym)

Marks the event-table column `sym` as a **channel-varying** predictor inside a formula. The
column must hold one value per channel in each row (e.g. `evts.bsl = [vals for _ in 1:size(evts,1)]`,
with `length(vals) == size(data,1)`).

The resulting designmatrix is fit per channel: shared predictors (e.g. `effect`) are identical
for all channels, while `bychannel` columns - and interactions involving them, e.g.
`effect*bychannel(bsl)` - vary per channel. The stored `modelmatrix` corresponds to the **first
channel**; the per-channel designmatrices are reconstructed during fitting.

Currently only supported for mass-univariate (epoched) models, not for time-expanded
(deconvolution) models. `predict` is not implemented for these models.

The typical application is channel-wise baseline regression (Alday et al., 2021): fit each
channel's epochs on its own baseline via e.g. `@formula(0 ~ 1 + effect + bychannel(bsl))`.

# Examples
```julia-repl
julia> data_e, times = Unfold.epoch(data=data, tbl=evts, τ=(-0.2, 1.5), sfreq=100)
julia> bsl_ix = findall(t -> t <= 0.0, times)
julia> evts.bsl = [vec(mean(data_e[:, bsl_ix, i]; dims = 2)) for i in axes(data_e, 3)]
julia> f = @formula 0 ~ 1 + condition + bychannel(bsl)
julia> m = fit(UnfoldLinearModel, [Any => (f, times)], evts, data_e)
```
"""
bychannel(x) = error(
    "`bychannel()` can only be used inside a formula, e.g. `@formula(0 ~ 1 + bychannel(bsl))`",
)

"""
    ChannelVaryingTerm <: AbstractTerm

Designmatrix term generated by `bychannel(sym)`. The referenced event-table column holds one
value per channel per row. When this term is present, evaluating the surrounding formula via
`modelcols` returns a channel-indexed designmatrix (`nch × rows × predictors`).
"""
struct ChannelVaryingTerm <: AbstractTerm
    sym::Symbol
end

Base.show(io::IO, t::ChannelVaryingTerm) = print(io, "bychannel(", t.sym, ")")

#---
# StatsModels glue code

function StatsModels.apply_schema(
    t::FunctionTerm{typeof(bychannel)},
    sch::StatsModels.Schema,
    Mod::Type{<:Any},
)
    ar = try
        t.args
    catch
        t.args_parsed # statsmodels < 0.7
    end
    term = only(ar)
    term isa StatsModels.Term || throw(
        ArgumentError(
            "bychannel() expects a single column name, e.g. `bychannel(bsl)` (got $(term))",
        ),
    )
    return ChannelVaryingTerm(term.sym)
end

StatsModels.termsyms(t::ChannelVaryingTerm) = Set([t.sym])
StatsModels.termvars(t::ChannelVaryingTerm) = [t.sym]
StatsModels.width(t::ChannelVaryingTerm) = 1
StatsAPI.coefnames(t::ChannelVaryingTerm) = string(t.sym)

#---
# helpers

"""
    _contains_channelterm(t)

Does the (schema-applied) term contain a `ChannelVaryingTerm`? Typified channel terms
(i.e. wrapped in an `Effects.TypicalTerm`) do not count, as they are evaluated by the
regular (non-channel-indexed) path.
"""
_contains_channelterm(t::ChannelVaryingTerm) = true
_contains_channelterm(t::InteractionTerm) = any(_contains_channelterm, t.terms)
_contains_channelterm(t::StatsModels.MatrixTerm) = any(_contains_channelterm, t.terms)
_contains_channelterm(t) = false

#---
# modelmatrix as stored in the DesignMatrix: for formulas containing bychannel terms this is
# the designmatrix of the **first channel** (2D); per-channel designmatrices are reconstructed
# during fitting via `modelcols_bychannel`

function _modelmatrix_cols(form::FormulaTerm, tbl)
    _contains_channelterm(form.rhs) || return modelcols(form.rhs, tbl)
    return modelcols_bychannel(form.rhs, tbl)[1, :, :]
end

"""
    modelcols_bychannel(term, tbl)

Evaluates a schema-applied designmatrix term containing `bychannel` terms and returns a
channel-indexed designmatrix `nch × nrows × ncols`. Shared terms are identical across channels,
while `bychannel` terms and interactions involving them vary per channel.

The column layout follows `coefnames(term)`, mirroring the `StatsModels` evaluation of
(interaction) terms.
"""
function modelcols_bychannel(t::StatsModels.MatrixTerm, tbl)
    parts = [_eval_bychannel(tt, tbl) for tt in t.terms]

    nch_ix = findfirst(p -> !isnothing(p[1]), parts)
    nch_ix === nothing && error("no channel-varying term found in $(t)")
    nch = parts[nch_ix][1]

    n = size(parts[nch_ix][2][1], 1)
    T = promote_type(eltype.(reduce(vcat, [p[2] for p in parts]))...)
    widths = [size(p[2][1], 2) for p in parts]

    X = zeros(T, nch, n, sum(widths))
    col = 0
    for (i, p) in enumerate(parts)
        w = widths[i]
        cols = (col+1):(col+w)
        if isnothing(p[1])
            # shared across channels
            X[:, :, cols] .= reshape(p[2][1], 1, n, w)
        else
            for ch = 1:nch
                X[ch, :, cols] .= p[2][ch]
            end
        end
        col += w
    end
    return X
end

# evaluate a single term into `(nch, per_channel_mats)`:
# shared terms => `(nothing, [n × p matrix])`
# channel-varying terms => `(nch, Vector of nch matrices, each n × p)`
_eval_bychannel(t::AbstractTerm, tbl) = (nothing, [modelcols(t, tbl)])

function _eval_bychannel(t::ChannelVaryingTerm, tbl)
    col = Tables.getcolumn(Tables.columntable(tbl), t.sym)
    lengths = length.(col)
    all(==(lengths[1]), lengths) || throw(
        ArgumentError(
            "column :$(t.sym) must contain the same number of values (channels) in every row, e.g. via `evts.$(t.sym) = [vals for _ in 1:size(evts,1)]`",
        ),
    )
    nch = lengths[1]
    chcols = reduce(hcat, col) # nch × n
    return nch, [reshape(view(chcols, ch, :), :, 1) for ch = 1:nch]
end

function _eval_bychannel(t::InteractionTerm, tbl)
    if !_contains_channelterm(t)
        return (nothing, [modelcols(t, tbl)])
    end
    subs = [_eval_bychannel(st, tbl) for st in t.terms]
    nchs = unique(filter(!isnothing, [s[1] for s in subs]))
    length(nchs) == 1 || throw(
        ArgumentError(
            "all channel-varying interaction terms need the same number of channels (got $(nchs))",
        ),
    )
    nch = nchs[1]
    return nch,
    [
        _channel_kron((s[1] === nothing ? s[2][1] : s[2][ch] for s in subs)...) for
        ch = 1:nch
    ]
end

# per-channel interaction, mirroring StatsModels.modelcols(InteractionTerm, ColumnTable)
# (kron-inside-out broadcast of the term matrices)
function _channel_kron(mats...)
    rows = size(mats[1], 1)
    reshaped = ntuple(
        i -> reshape(mats[i], size(mats[i], 1), ones(Int, i - 1)..., :),
        length(mats),
    )
    return reshape(broadcast(*, reshaped...), rows, :)
end

#---
# Effects glue code
# channel-varying terms are fixed to 0 in `effects`, i.e. effects are reported conditional
# on them. If a bychannel predictor is given in the effects reference-grid, its grid values
# are ignored (with a warning).

import Effects

"""
    _zerobychannel_typify(form, reference_grid)

Replaces channel-varying terms in a (typified) formula with their zero-typical version, so
`effects` reports effects **conditional** on them. Warns if a bychannel predictor was given
in the reference-grid, as its values are then ignored.
"""
function _zerobychannel_typify(t::StatsModels.MatrixTerm, reference_grid)
    return StatsModels.MatrixTerm(_zerobychannel_typify.(t.terms, Ref(reference_grid)))
end
function _zerobychannel_typify(t::InteractionTerm, reference_grid)
    return InteractionTerm(_zerobychannel_typify.(t.terms, Ref(reference_grid)))
end
function _zerobychannel_typify(t::ChannelVaryingTerm, reference_grid)
    if t.sym ∈ Tables.columnnames(reference_grid)
        @warn "bychannel predictor :$(t.sym) was given in the effects reference-grid, but its values are ignored: effects are computed conditional on it (fixed to 0)."
    end
    return Effects.TypicalTerm(t, [0.0])
end
function _zerobychannel_typify(t::Effects.TypicalTerm, reference_grid)
    return t.term isa ChannelVaryingTerm ? Effects.TypicalTerm(t.term, [0.0]) : t
end
_zerobychannel_typify(t, reference_grid) = t
